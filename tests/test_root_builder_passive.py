"""Keep cold copied-profile semantics when MO2 registers known disabled mods."""
from contextlib import ExitStack
from hashlib import sha256
from pathlib import Path
from tempfile import TemporaryDirectory
from types import SimpleNamespace
import unittest
from unittest.mock import Mock, patch

from skyrim_autotest import editions, root_builder_passive as passive


HEADER = b'# This file was automatically generated by Mod Organizer.\r\n'
ORIGINAL = HEADER + b'+Enabled\r\n-Existing disabled\r\n-_separator\r\n*DLC: Dawnguard\r\n'
REGISTERED = HEADER + b'-Already installed\r\n' + ORIGINAL[len(HEADER):]


class DisabledRegistrationTests(unittest.TestCase):
    def test_raw_lines_markers_comments_bom_and_order_are_preserved(self):
        additions = passive._registered_disabled_mods(ORIGINAL, REGISTERED, {'Already installed': [1, 21]})
        self.assertEqual(additions, ['Already installed'])
        bom = b'\xef\xbb\xbf'
        self.assertEqual(passive._registered_disabled_mods(bom + ORIGINAL, bom + REGISTERED, {'Already installed'}),
                         ['Already installed'])
        self.assertEqual(passive._registered_disabled_mods(ORIGINAL, ORIGINAL, set()), [])

    def test_even_a_real_directory_cannot_enable_reorder_or_relabel_original_rows(self):
        rejected = (
            REGISTERED.replace(b'-Already installed', b'+Already installed'),
            REGISTERED.replace(b'+Enabled', b'-Enabled'),
            REGISTERED.replace(b'-Existing disabled\r\n', b''),
            REGISTERED.replace(b'-Existing disabled', b'-EXISTING disabled'),
            REGISTERED.replace(b'\r\n', b'\n'),
            REGISTERED.replace(HEADER, b'# changed\r\n'),
            b'\xef\xbb\xbf' + REGISTERED,
            REGISTERED.replace(b'+Enabled\r\n-Existing disabled', b'-Existing disabled\r\n+Enabled'),
            REGISTERED.replace(b'-Already installed', b'-Already installed\r\n-already installed'),
            REGISTERED.replace(b'-Already installed', b'-Heading_separator'),
            REGISTERED.replace(b'-Already installed', b'-..\\Already installed'),
        )
        for current in rejected:
            with self.subTest(current=current), self.assertRaises(ValueError):
                passive._registered_disabled_mods(ORIGINAL, current, {'Already installed', 'Heading_separator'})
        with self.assertRaises(ValueError):
            passive._registered_disabled_mods(ORIGINAL, REGISTERED, {'already installed'})


class PassiveBootRegistrationTests(unittest.TestCase):
    def setUp(self):
        self.stack = ExitStack()
        self.addCleanup(self.stack.close)
        home = Path(self.stack.enter_context(TemporaryDirectory()))
        self.mods = home / 'mods'
        self.mods.mkdir()
        for name in ('Enabled', 'Existing disabled', 'Already installed'):
            (self.mods / name).mkdir()
        profiles = home / 'profiles'
        source, copy = profiles / 'original', profiles / 'Autotest-case'
        source.mkdir(parents=True)
        copy.mkdir()
        self.source, self.copy = source / 'modlist.txt', copy / 'modlist.txt'
        self.source.write_bytes(ORIGINAL)
        self.copy.write_bytes(ORIGINAL)
        (copy / 'plugins.txt').write_bytes(b'*Original.esp\r\n')
        (copy / 'loadorder.txt').write_bytes(b'Original.esp\r\n')
        ini = home / 'ModOrganizer.ini'
        ini.write_text('[Plugins]\n', encoding='utf-8')
        exe = home / 'ModOrganizer.exe'
        loader = {'name': 'SKSE', 'target': 'pinned'}
        contract = {'profile': str(source), 'profileModlistSha256': sha256(ORIGINAL).hexdigest(),
                    'paths': {'mo2_exe': str(exe)}, 'loaderContract': loader}
        self.record = {'runId': 'case', 'contract': contract, 'contractSha256': passive.rb._digest(contract),
                       'phase': 'prepared'}
        self.session = SimpleNamespace(dir=home / 'run', save=Mock(), state={
            'id': 'case', 'testProfile': str(copy), 'rootBuilderPassive': self.record,
            'configuration': {'mods': str(self.mods), 'profiles': str(profiles), 'mo2_ini': str(ini),
                              'overwrite': str(home / 'overwrite')},
        })
        for name in ('cold_idle', '_unchanged'):
            self.stack.enter_context(patch.object(passive, name))
        self.stack.enter_context(patch.object(passive, '_off', return_value={'autobuild': 'false'}))
        self.stack.enter_context(patch.object(editions, 'validate_mo2_loader', return_value=loader))
        self.identity = self.stack.enter_context(patch.object(passive.native, 'identity'))
        passive.before_launch(self.session)
        owner = {'pid': 99, 'path': str(exe), 'birth': self.record['coldStartProof']['minimumProcessBirth']}
        self.identity.return_value = owner
        self.session.state['owned'] = [{'role': 'mo2', 'identity': owner}]
        self.bridge = {'mo2Pid': 99, 'serverBootId': 'current', 'instanceId': 'owned', 'profilesPath': str(profiles)}

    def test_exact_real_cold_and_post_inventory_only_accepts_disabled_insert(self):
        self.copy.write_bytes(REGISTERED)
        passive.verify_boot(self.session, self.bridge)
        proof = self.record['effectiveSettingsProof']
        self.assertEqual(self.record['phase'], 'verified-before-game')
        self.assertEqual(proof['registeredDisabledMods'], ['Already installed'])
        self.assertEqual(Path(proof['profileModlist']['path']).read_bytes(), ORIGINAL)
        self.assertEqual(Path(proof['postBootProfileModlist']['path']).read_bytes(), REGISTERED)
        self.assertEqual(self.source.read_bytes(), ORIGINAL)
        self.assertEqual(self.copy.read_bytes(), REGISTERED)

    def test_a_late_directory_cannot_authorize_a_disabled_row(self):
        (self.mods / 'New after startup').mkdir()
        self.copy.write_bytes(REGISTERED.replace(b'Already installed', b'New after startup'))
        with self.assertRaisesRegex(ValueError, 'directory evidence changed'):
            passive.verify_boot(self.session, self.bridge)

    def test_same_name_cannot_hide_a_replaced_installed_directory(self):
        previous = self.mods / 'Already installed'
        previous.rename(self.mods.parent / 'previous directory')
        previous.mkdir()
        self.copy.write_bytes(REGISTERED)
        with self.assertRaisesRegex(ValueError, 'directory evidence changed'):
            passive.verify_boot(self.session, self.bridge)

    def test_modified_cold_modlist_evidence_cannot_authorize_an_insert(self):
        path = Path(self.record['coldStartProof']['profileModlist']['path'])
        path.write_bytes(REGISTERED)
        self.copy.write_bytes(REGISTERED)
        with self.assertRaisesRegex(ValueError, 'modlist or installed mod directory evidence changed'):
            passive.verify_boot(self.session, self.bridge)

    def test_source_drift_cannot_be_masked_by_disabled_insert(self):
        self.source.write_bytes(REGISTERED)
        self.copy.write_bytes(REGISTERED)
        with self.assertRaisesRegex(ValueError, 'Source profile modlist changed'):
            passive.verify_boot(self.session, self.bridge)

    def test_disabled_insert_cannot_mask_plugin_order_drift(self):
        (self.copy.parent / 'loadorder.txt').write_bytes(b'New.esp\r\nOriginal.esp\r\n')
        self.copy.write_bytes(REGISTERED)
        with self.assertRaisesRegex(ValueError, 'plugins.txt or loadorder.txt changed'):
            passive.verify_boot(self.session, self.bridge)

    def test_original_exact_bytes_keep_the_older_cold_proof_contract(self):
        self.record['coldStartProof'].pop('profileModlist')
        self.record['coldStartProof'].pop('installedModDirs')
        self.record['coldStartProof'].pop('profilePluginOrder')
        (self.copy.parent / 'plugins.txt').write_bytes(b'*Different.esp\r\n')
        passive.verify_boot(self.session, self.bridge)
        self.assertEqual(self.record['effectiveSettingsProof']['registeredDisabledMods'], [])
